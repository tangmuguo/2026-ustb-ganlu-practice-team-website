package com.vihu.ganlu.entitys;

public class TeamYearSummary {
    private String year;
    private String coverUrl;
    private Integer publishedTeamCount;

    public String getYear() {
        return year;
    }

    public void setYear(String year) {
        this.year = year;
    }

    public String getCoverUrl() {
        return coverUrl;
    }

    public void setCoverUrl(String coverUrl) {
        this.coverUrl = coverUrl;
    }

    public Integer getPublishedTeamCount() {
        return publishedTeamCount;
    }

    public void setPublishedTeamCount(Integer publishedTeamCount) {
        this.publishedTeamCount = publishedTeamCount;
    }
}
